/** Map an OS locale ("zh-CN", "zh_Hans_CN", "en-US", …) to a supported code. */
function normalizeLocale(locale) {
  const raw = String(locale || '').replace('_', '-').toLowerCase();
  if (!raw) return 'en';
  if (raw === 'zh' || raw.startsWith('zh-')) return 'zh-CN';
  if (raw.startsWith('fr')) return 'fr';
  if (raw.startsWith('es')) return 'es';
  if (raw.startsWith('ru')) return 'ru';
  if (raw.startsWith('ar')) return 'ar';
  if (raw.startsWith('en')) return 'en';
  return 'en';
}

/**
 * Translation function. Missing keys fall back to English, then to the key
 * itself, so a partial translation never shows a blank label.
 */
function createTranslator(locale) {
  const code = MESSAGES[locale] ? locale : normalizeLocale(locale);
  const table = MESSAGES[code] || en;
  const t = (key, vars) => {
    let s = table[key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] != null ? String(vars[name]) : m));
    }
    return s;
  };
  t.locale = code;
  return t;
}

