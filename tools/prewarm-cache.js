'use strict';

/**
 * prewarm-cache.js — offline-friendly helper for restricted Windows machines.
 *
 * electron-builder downloads tool archives with symlinks (macOS dylibs) that a
 * non-elevated Windows account cannot create, so unpacking them fails even
 * though every Windows-relevant file is fine. The archives cache by a
 * checksum-named directory; we unpack them ahead of time (symlinks failing is
 * harmless) and remember the checksum so the build reuses the directory.
 *
 *   node tools/prewarm-cache.js
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const cache = process.env.ELECTRON_BUILDER_CACHE || path.join(process.env.LOCALAPPDATA || '', 'electron-builder', 'Cache');
const sevenZip = path.join(__dirname, '..', 'node_modules', '7zip-bin', 'win', 'x64', '7za.exe');
const BINARIES = process.env.ELECTRON_BUILDER_BINARIES_MIRROR || 'https://npmmirror.com/mirrors/electron-builder-binaries/';

const ARTIFACTS = [
  ['winCodeSign', '2.6.0'],
  ['nsis', '3.0.4.1'],
  ['nsis-resources', '3.4.1'],
];

(async () => {
  if (!fs.existsSync(cache)) fs.mkdirSync(cache, { recursive: true });
  for (const [name, version] of ARTIFACTS) {
    const dirName = `${name}-${version}`;
    const dir = path.join(cache, dirName);
    const stamp = path.join(cache, `${name}.sha512`);
    // reuse an archive electron-builder already fetched (any checksum bucket)
    let tmp = path.join(cache, `${dirName}.tmp.7z`);
    if (!fs.existsSync(dir) || !fs.existsSync(stamp)) {
      const buckets = path.join(cache, name);
      const existing = fs.existsSync(buckets)
        ? fs.readdirSync(buckets).find((f) => f.endsWith('.7z'))
        : null;
      if (existing) tmp = path.join(buckets, existing);
      else {
        console.log(`• 下载 ${dirName} …`);
        // follow redirects with the bundled app-builder (handles mirrors + TLS)
        execFileSync(
          path.join(__dirname, '..', 'node_modules', 'app-builder-bin', 'win', 'x64', 'app-builder.exe'),
          ['download', '--url', url, '--output', tmp],
          { stdio: 'inherit' }
        );
      }
    }
    if (fs.existsSync(dir) && fs.existsSync(stamp)) {
      console.log(`• ${dirName} 已就绪`);
      continue;
    }
    const sha512 = require('crypto').createHash('sha512').update(fs.readFileSync(tmp)).digest('base64');
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });
    try {
      execFileSync(sevenZip, ['x', '-y', '-bd', tmp, `-o${dir}`], { stdio: 'ignore' });
    } catch {
      // symlink creation for macOS dylibs fails without privileges — not needed
    }
    fs.rmSync(tmp, { force: true });
    fs.writeFileSync(stamp, sha512);

    // electron-builder only consults this when a signing certificate is set;
    // pointing it at the pre-extracted copy makes the build independent of the
    // symlink problem for CI and for `signAndEditExecutable`.
    if (name === 'winCodeSign') {
      const yml = [
        '# generated by tools/prewarm-cache.js',
        `path: "${dir.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`,
        `sha512: "${sha512}"`,
        '',
      ].join('\n');
      fs.writeFileSync(path.join(cache, 'winCodeSign.yml'), yml);
    }
    console.log(`✔ ${dirName} 已解压（校验和 ${sha512.slice(0, 12)}…）`);
  }
})();
